import { Parser, Language, Query } from 'web-tree-sitter';
const base = '/tmp/claude-1000/-workspace/29babd88-0ee3-42fc-9906-f088e1d90ef2/scratchpad/jvm/';
await Parser.init();
const java = await Language.load(base + 'node_modules/tree-sitter-java/tree-sitter-java.wasm');
const ktG = await Language.load(base + 'node_modules/@tree-sitter-grammars/tree-sitter-kotlin/tree-sitter-kotlin.wasm');
const ktH = await Language.load(base + 'build/tree-sitter-kotlin.wasm');
const p = new Parser();
p.setLanguage(java);
const jt = p.parse('import module java.base;\nimport static a.B.*;\nclass X {}\n');
console.log('java module import:', jt.rootNode.toString());
const jq = new Query(java, '(import_declaration "static"? @static [(identifier) (scoped_identifier)] @name (asterisk)? @wildcard) @imp');
for (const m of jq.matches(p.parse('import static a.B.c;\nimport a.b.*;\nimport a.b.C;').rootNode)) console.log('java match', m.captures.map(c => c.name + '=' + c.node.text).join(' '));
const ksrc = 'package a.b\nimport x.y.Z as W\nimport x.y.*\nimport x.`fun`.Q\n';
p.setLanguage(ktG);
console.log('ktG:', p.parse(ksrc).rootNode.toString());
const gq = new Query(ktG, '(import (qualified_identifier) @name "*"? @wildcard (identifier)? @alias) @imp');
for (const m of gq.matches(p.parse(ksrc).rootNode)) console.log('ktG match', m.captures.map(c => c.name + '=' + c.node.text).join(' '));
p.setLanguage(ktH);
const hq = new Query(ktH, '(import_header (identifier) @name (wildcard_import)? @wildcard (import_alias (type_identifier) @alias)?) @imp');
for (const m of hq.matches(p.parse(ksrc).rootNode)) console.log('ktHead match', m.captures.map(c => c.name + '=' + c.node.text).join(' '));
